import mpmath as mp
mp.mp.dps = 50

# SU(2) irreps labeled by j = 0,1/2,1,... ; dim d=2j+1 ; Casimir C2=j(j+1).
# Heat-kernel single-plaquette coefficients (single coupling t=-log w>0, weak=small t):
#   c_a = d_a * exp(-t*C2_a),  reduced eigenvalue f_a = c_a/d_a = exp(-t*C2_a).
# A single-coupling (heat-kernel) action <=> log f_s / C2_s = const (=-t) for all s.
#
# GENUINE SU(2) block fusion of two parallel fine plaquettes threading one coarse
# holonomy U: the coarse class function is the POINTWISE PRODUCT K_t(U)^2.
# Character coefficients fuse by Clebsch-Gordan (chi_a*chi_b = sum_{c=|a-b|}^{a+b} chi_c):
#   c'_c = sum_{a,b : |a-b|<=c<=a+b, a+b+c even} c_a c_b .
# Heat kernels are a semigroup under CONVOLUTION, NOT pointwise product, so K_t^2 is
# generically NOT heat-kernel: the deviation of log f'_s from linearity in C2_s IS the
# induced (multi-rep) coupling generated by one block step.

def dim(twoj):  # label s=2j integer
    return twoj+1
def C2(twoj):   # j(j+1) with j=s/2
    j = mp.mpf(twoj)/2
    return j*(j+1)

def heat_coeffs(t, Smax):
    return {s: dim(s)*mp.e**(-t*C2(s)) for s in range(Smax+1)}

def fuse_pointwise_square(c, Smax):
    # c'_s = sum over a,b with s in a (x) b (SU(2) CG, mult 1)
    cp = {s: mp.mpf(0) for s in range(Smax+1)}
    amax = max(c.keys())
    for a in range(amax+1):
        for b in range(amax+1):
            # c ranges |a-b|..a+b step 2
            lo=abs(a-b); hi=a+b
            cc=lo
            while cc<=hi:
                if cc<=Smax:
                    cp[cc]+=c[a]*c[b]
                cc+=2
    return cp

def induced_report(w):
    t=-mp.log(w)
    Smax=8
    Sint=40   # internal truncation for the fusion sum (reps summed to high order)
    c=heat_coeffs(t,Sint)
    cp=fuse_pointwise_square(c,Smax)
    # reduced eigenvalues of coarse action
    fp={s: cp[s]/dim(s) for s in range(1,Smax+1)}
    # "effective single coupling" from the s=1 channel:  t' := -log f'_1 / C2_1
    tp = -mp.log(fp[1])/C2(1)
    # induced coupling in channel s = deviation of -log f'_s/C2_s from t' (single-coupling residual)
    dev={}
    for s in range(1,Smax+1):
        ts = -mp.log(fp[s])/C2(s)
        dev[s]= ts - tp     # 0 for all s <=> exact single coupling
    # leading induced coupling magnitude (s=2 channel, first non-fundamental)
    lead = dev[2]
    return t,tp,dev,lead

print("### FIELD-SPACE (heat-kernel) induced coupling under genuine SU(2) block fusion K_t^2")
print("  columns: w   (1-w)   t=-logw   t'(eff)   dev_s2   dev_s3   dev_s2/t   dev_s2/t^2")
for w in ['0.5','0.7','0.9','0.95','0.99','0.999','0.9999']:
    wv=mp.mpf(w)
    t,tp,dev,lead=induced_report(wv)
    print(f"  w={w:8} 1-w={mp.nstr(1-wv,4):8} t={mp.nstr(t,5):9} t'={mp.nstr(tp,5):9} "
          f"dev2={mp.nstr(dev[2],5):10} dev3={mp.nstr(dev[3],5):10} "
          f"dev2/t={mp.nstr(dev[2]/t,5):9} dev2/t^2={mp.nstr(dev[2]/t**2,6):9}")
