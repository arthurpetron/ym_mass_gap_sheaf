#!/usr/bin/env python3
"""Assemble global pointwise E8/E9 relations from seven-row Lean slices."""

from __future__ import annotations

from pathlib import Path

from lower_six_tail_second_flux_certificate import MODE_CHART_BASE


ROW_SHARD_SIZE = 7
CASES = [
    ("E8", "A", 83, 44, MODE_CHART_BASE),
    ("E9", "A", 87, 44, MODE_CHART_BASE),
    ("E8", "B", 85, 44, MODE_CHART_BASE),
    ("E9", "B", 87, 44, MODE_CHART_BASE),
]


def branch_header(shard: int, start: int, stop: int, last: bool) -> list[str]:
    if shard == 0:
        return [f"  by_cases h{shard} : i < {stop}", "  ·"]
    outer = " " * (2 * shard)
    if last:
        return [f"{outer}· have h{shard} : i < {stop} := hi"]
    inner = " " * (2 * (shard + 1))
    return [f"{outer}· by_cases h{shard} : i < {stop}", f"{inner}·"]


def branch_indent(shard: int, last: bool) -> str:
    if shard == 0:
        return "    "
    return " " * (2 * (shard + 1 if last else shard + 2))


def render_relation_branches(
    stem: str,
    gate: str,
    aggregate_gate: str,
    degree_x: int,
    degree_y: int,
    shard_count: int,
    kind: str,
    constant: int,
) -> list[str]:
    lines: list[str] = []
    for shard in range(shard_count):
        start = shard * ROW_SHARD_SIZE
        stop = min(start + ROW_SHARD_SIZE, degree_x + 1)
        height = stop - start
        last = shard == shard_count - 1
        lines.extend(branch_header(shard, start, stop, last))
        indent = branch_indent(shard, last)
        local = f"i - {start}"
        if kind == "nonnegative":
            lines.extend([
                f"{indent}have hlocal := gridNonnegative_true_at",
                f"{indent}  {stem}_nonnegative_slice{shard}",
                f"{indent}  (i := {local}) (j := j) (by omega) hj",
            ])
        else:
            lines.extend([
                f"{indent}have hlocal := gridRelationSlice_true_at",
                f"{indent}  {stem}_{gate}_slice{shard}",
                f"{indent}  (localRow := {local}) (j := j) (by omega) hj",
            ])
        lines.extend([
            f"{indent}have hagg := gridRelationSlice_true_at",
            f"{indent}  {stem}_{aggregate_gate}_aggregate_slice{shard}",
            f"{indent}  (localRow := {local}) (j := j) (by omega) hj",
            f"{indent}have hindex : {start} + ({local}) = i := by omega",
            f"{indent}rw [hindex] at hagg",
        ])
        if kind != "nonnegative":
            lines.append(f"{indent}rw [hindex] at hlocal")
        if kind in {"x", "shift"}:
            lines.append(
                f"{indent}exact Eq.trans (Eq.symm hagg) hlocal"
            )
        elif kind == "y":
            lines.extend([
                f"{indent}have hlift := congrArg (fun coefficient : Int =>",
                f"{indent}  coefficient * Int.ofNat",
                f"{indent}    (binom {degree_x} i * binom {degree_y} j)) hagg",
                f"{indent}unfold weightedGrid",
                f"{indent}exact Eq.trans (Eq.symm hlift) hlocal",
            ])
        elif kind == "nonnegative":
            lines.extend([
                f"{indent}rw [hagg] at hlocal",
                f"{indent}exact hlocal",
            ])
        elif kind == "raw":
            lines.extend([
                f"{indent}have hlift := congrArg (fun coefficient : Int =>",
                f"{indent}  coefficient * Int.ofNat ({constant} ^ i)) hagg",
                f"{indent}exact Eq.trans (Eq.symm hlift) hlocal",
            ])
        elif kind == "affine":
            lines.extend([
                f"{indent}have hlift := congrArg (fun coefficient : Int =>",
                f"{indent}  coefficient * Int.ofNat ({2 * MODE_CHART_BASE} ^ {degree_y})) hagg",
                f"{indent}exact Eq.trans (Eq.symm hlift) hlocal",
            ])
        else:
            raise AssertionError(kind)
    return lines


def render(label: str, chart: str, degree_x: int, degree_y: int,
           constant: int) -> str:
    stem = f"tailEnvelope{label}Chart{chart}"
    namespace = (
        "YMGap.Continuum."
        f"HarmonicLowerSixTailEnvelopeCertificate{label}Chart{chart}"
    )
    shard_count = (degree_x + ROW_SHARD_SIZE) // ROW_SHARD_SIZE
    module_prefix = (
        f"YMGap.Continuum.HarmonicLowerSixTailEnvelopeCertificate{label}"
        f"Chart{chart}"
    )
    lines = [
        "/-",
        f"# Global exact coefficient certificate for {label} chart {chart}",
        "",
        "Generated by",
        "`computations/generate_lower_six_tail_envelope_global_certificates.py`.",
        "-/",
        "",
    ]
    for shard in range(shard_count):
        lines.append(f"import {module_prefix}Slice{shard}")
        lines.append(f"import {module_prefix}AggregateSlice{shard}")
    lines.extend([
        "",
        f"namespace {namespace}",
        "",
        "open YMGap.RG",
        "open YMGap.Continuum.TensorBernsteinSeparableReconstruction",
        "open YMGap.Continuum.HarmonicLowerSixTailEnvelopeCoefficientKernel",
        "open YMGap.Continuum.HarmonicLowerSixTailEnvelopeCertificateRows",
        "",
        f"theorem {stem}_xPascal_at {{i j : Nat}}",
        f"    (hi : i < {degree_x + 1}) (hj : j < {degree_y + 1}) :",
        f"    gridCoeff {stem}XPascalRows i j =",
        f"      xPascalExpected {degree_x} {stem}ScaledPowerRows i j := by",
    ])
    lines.extend(render_relation_branches(
        stem, "xPascal", "xPascal", degree_x, degree_y, shard_count,
        "x", constant
    ))
    lines.extend([
        "",
        f"theorem {stem}_yPascal_at {{i j : Nat}}",
        f"    (hi : i < {degree_x + 1}) (hj : j < {degree_y + 1}) :",
        f"    weightedGrid {degree_x} {degree_y} {stem}BernsteinRows i j =",
        f"      yPascalExpected {degree_y} {stem}XPascalRows i j := by",
    ])
    lines.extend(render_relation_branches(
        stem, "yPascal", "bernstein", degree_x, degree_y, shard_count,
        "y", constant
    ))
    lines.extend([
        "",
        f"theorem {stem}_nonnegative_at {{i j : Nat}}",
        f"    (hi : i < {degree_x + 1}) (hj : j < {degree_y + 1}) :",
        f"    (0 : Int) ≤ gridCoeff {stem}BernsteinRows i j := by",
    ])
    lines.extend(render_relation_branches(
        stem, "nonnegative", "bernstein", degree_x, degree_y, shard_count,
        "nonnegative", constant
    ))
    if chart == "A":
        lines.extend([
            "",
            f"theorem {stem}_shift_at {{i j : Nat}}",
            f"    (hi : i < {degree_x + 1}) (hj : j < {degree_y + 1}) :",
            f"    gridCoeff {stem}ScaledPowerRows i j =",
            f"      upperBinomialTransform {degree_y}",
            f"        (fun exponent => gridCoeff {stem}PreChartRows i exponent) j := by",
        ])
        lines.extend(render_relation_branches(
            stem, "shift", "power", degree_x, degree_y, shard_count,
            "shift", constant
        ))
    else:
        lines.extend([
            "",
            f"theorem {stem}_affine_at {{i j : Nat}}",
            f"    (hi : i < {degree_x + 1}) (hj : j < {degree_y + 1}) :",
            f"    gridCoeff {stem}ScaledPowerRows i j *",
            f"        Int.ofNat ({2 * MODE_CHART_BASE} ^ {degree_y}) =",
            f"      affineChartBClearedCoeff {degree_y} {stem}PreChartRows i j := by",
        ])
        lines.extend(render_relation_branches(
            stem, "affine", "power", degree_x, degree_y, shard_count,
            "affine", constant
        ))
    lines.extend([
        "",
        f"theorem {stem}_raw_at {{i j : Nat}}",
        f"    (hi : i < {degree_x + 1}) (hj : j < {degree_y + 1}) :",
        f"    gridCoeff {stem}PreChartRows i j * Int.ofNat ({constant} ^ i) =",
        f"      quadraticRawExpected 89 {stem}ChartQuotient",
        f"        tailEnvelope{label}ClearedRows i j := by",
    ])
    lines.extend(render_relation_branches(
        stem, "raw", "preChart", degree_x, degree_y, shard_count,
        "raw", constant
    ))
    lines.extend([
        "",
        f"theorem {stem}_scale_relation :",
        f"    {stem}TableScale = {stem}ClearScale * {stem}ChartQuotient := by",
        "  decide",
        "",
        f"theorem {stem}_transform_at {{i j : Nat}}",
        f"    (hi : i < {degree_x + 1}) (hj : j < {degree_y + 1}) :",
        f"    weightedGrid {degree_x} {degree_y} {stem}BernsteinRows i j =",
        f"      tensorPascalTransform {degree_x} {degree_y}",
        f"        (gridCoeff {stem}ScaledPowerRows) i j := by",
        f"  have hy := {stem}_yPascal_at hi hj",
        "  exact Eq.trans hy (by",
        f"    unfold yPascalExpected tensorPascalTransform tensorPascalMid",
        f"    exact pascalTransformRow_congr {degree_y}",
        f"      (fun b => gridCoeff {stem}XPascalRows i b)",
        f"      (fun b => pascalTransformRow {degree_x}",
        f"        (fun a => gridCoeff {stem}ScaledPowerRows a b) i)",
        f"      j (fun b hb => {stem}_xPascal_at hi hb))",
        "",
    ])
    gates = ["xPascal_at", "yPascal_at", "nonnegative_at"]
    gates.append("shift_at" if chart == "A" else "affine_at")
    gates.extend(["raw_at", "scale_relation", "transform_at"])
    for gate in gates:
        lines.append(f"#print axioms {stem}_{gate}")
    lines.extend(["", f"end {namespace}", ""])
    return "\n".join(lines)


def main() -> None:
    repo = Path(__file__).resolve().parents[1]
    continuum = repo / "lean" / "YMGap" / "Continuum"
    for label, chart, degree_x, degree_y, constant in CASES:
        path = continuum / (
            f"HarmonicLowerSixTailEnvelopeCertificate{label}Chart{chart}"
            "CoefficientCertificate.lean"
        )
        path.write_text(render(label, chart, degree_x, degree_y, constant))
        print(path.name)


if __name__ == "__main__":
    main()
