"""Generate Lean data and row shards for the exact physical 65x65 kernel.

The Python contraction is an untrusted producer.  Each generated Lean row
recomputes the genuine 140-factor ternary elimination recurrence in the kernel
and compares all 65 entries with the proposed literal table.  The root theorem
then exposes the checked equality at arbitrary in-range indices.
"""

from __future__ import annotations

import argparse
from fractions import Fraction
from pathlib import Path

from computations.bf4_cutoff_two_65_sector_ldl_certificate import (
    _exact_kernel,
    _lean_q,
)


def _array_definition(name: str, values: list[Fraction]) -> str:
    lines = [f"def {name} : Array Q' := #["]
    width = 3
    for start in range(0, len(values), width):
        chunk = ", ".join(_lean_q(value) for value in values[start:start + width])
        suffix = "," if start + width < len(values) else ""
        lines.append(f"  {chunk}{suffix}")
    lines.append("]")
    return "\n".join(lines)


def _or_cases(size: int) -> str:
    return " ∨\n      ".join(f"row = {row}" for row in range(size))


def render_bundle(*, coupling: Fraction, jobs: int) -> tuple[
    str, tuple[str, ...], str
]:
    kernel, row_sums = _exact_kernel(coupling, jobs)
    size = len(kernel)
    if size != 65:
        raise AssertionError(f"expected 65 states, got {size}")
    kernel_values = [kernel[row][column]
                     for row in range(size) for column in range(size)]

    data_source = f'''/-
# Exact cutoff-two 65-sector raw physical kernel data

Generated by
`computations/bf4_cutoff_two_65_sector_raw_kernel_certificate.py`.
The producer is untrusted.  The row modules recompute the verified genuine
140-factor recurrence and compare all entries in Lean.
-/

import YMGap.Continuum.BF4PhysicalBoundaryCutoffTwoSectorComputedKernel

namespace YMGap.Continuum.BF4PhysicalBoundaryCutoffTwoSectorRawKernelCertificate

set_option maxRecDepth 1000000
set_option maxHeartbeats 1000000000

open YMGap.Constructive
open YMGap.Continuum.BF4PhysicalBoundaryCutoffTwoCubeSubsetEnumeration
open YMGap.Continuum.BF4PhysicalBoundaryCutoffTwoSectorComputedKernel
open YMGap.Continuum.BF4PhysicalBoundaryCutoffTwoSectorFactorGraph
open YMGap.Continuum.FiniteScopedFactorComputedTernaryElimination
open YMGap.Continuum.SU2FiniteTrivalentPacketGraphActualOperator

local infix:50 " ≈ " => Q'.eqv

{_array_definition("cutoffTwoSectorRawKernelData", kernel_values)}

{_array_definition("cutoffTwoSectorRawRowSumData", list(row_sums))}

def cutoffTwoSectorRawKernel (row column : Nat) : Q' :=
  cutoffTwoSectorRawKernelData.getD (row * {size} + column) 0

def cutoffTwoSectorRawRowSum (row : Nat) : Q' :=
  cutoffTwoSectorRawRowSumData.getD row 0

def cutoffTwoSectorStateAt (index : Nat) :=
  cutoffTwoCubeSectorStates.getD index zeroEdgeLabelling

def cutoffTwoSectorComputedRawKernel (row column : Nat) : Q' :=
  let left := cutoffTwoSectorStateAt row
  let right := cutoffTwoSectorStateAt column
  (cutoffTwoLowerFaceScalar left * cutoffTwoLowerFaceScalar right) *
    cutoffTwoSectorPairComputedInterface left right

def cutoffTwoSectorRawKernelRowCheck (row : Nat) : Bool :=
  (List.range {size}).all fun column =>
    decide (cutoffTwoSectorComputedRawKernel row column ≈
      cutoffTwoSectorRawKernel row column)

theorem cutoffTwoSectorRawKernelRowCheck_sound
    {{row column : Nat}}
    (hcheck : cutoffTwoSectorRawKernelRowCheck row = true)
    (hcolumn : column < {size}) :
    cutoffTwoSectorComputedRawKernel row column ≈
      cutoffTwoSectorRawKernel row column := by
  unfold cutoffTwoSectorRawKernelRowCheck at hcheck
  exact of_decide_eq_true
    (List.all_eq_true.mp hcheck column (List.mem_range.mpr hcolumn))

end YMGap.Continuum.BF4PhysicalBoundaryCutoffTwoSectorRawKernelCertificate
'''

    row_sources = tuple(f'''/- Generated raw-kernel row {row}. -/
import YMGap.Continuum.BF4PhysicalBoundaryCutoffTwoSectorRawKernelData

namespace YMGap.Continuum.BF4PhysicalBoundaryCutoffTwoSectorRawKernelCertificate

set_option maxRecDepth 1000000
set_option maxHeartbeats 1000000000

theorem cutoffTwoSectorRawKernelRow{row:02d}_checked :
    cutoffTwoSectorRawKernelRowCheck {row} = true := by
  decide

end YMGap.Continuum.BF4PhysicalBoundaryCutoffTwoSectorRawKernelCertificate

#print axioms
  YMGap.Continuum.BF4PhysicalBoundaryCutoffTwoSectorRawKernelCertificate.cutoffTwoSectorRawKernelRow{row:02d}_checked
''' for row in range(size))

    imports = "\n".join(
        f"import YMGap.Continuum.BF4PhysicalBoundaryCutoffTwoSectorRawKernelRows.Row{row:02d}"
        for row in range(size)
    )
    proof_alternatives = " | ".join(
        f"exact cutoffTwoSectorRawKernelRow{row:02d}_checked"
        for row in range(size)
    )
    root_source = f'''/-
# Exact cutoff-two 65-sector raw physical kernel certificate

All 65 row checks are separate build shards.  The theorem below combines them
without rerunning any entry computation.
-/

{imports}

namespace YMGap.Continuum.BF4PhysicalBoundaryCutoffTwoSectorRawKernelCertificate

set_option maxRecDepth 1000000
set_option maxHeartbeats 1000000000

open YMGap.Constructive

local infix:50 " ≈ " => Q'.eqv

theorem cutoffTwoSectorRawKernelRows_checked
    (row : Nat) (hrow : row < {size}) :
    cutoffTwoSectorRawKernelRowCheck row = true := by
  have hcases :
      {_or_cases(size)} := by
    omega
  rcases hcases with {" | ".join("rfl" for _ in range(size))}
  all_goals first | {proof_alternatives}

theorem cutoffTwoSectorComputedRawKernel_eqv_raw
    {{row column : Nat}} (hrow : row < {size}) (hcolumn : column < {size}) :
    cutoffTwoSectorComputedRawKernel row column ≈
      cutoffTwoSectorRawKernel row column :=
  cutoffTwoSectorRawKernelRowCheck_sound
    (cutoffTwoSectorRawKernelRows_checked row hrow) hcolumn

end YMGap.Continuum.BF4PhysicalBoundaryCutoffTwoSectorRawKernelCertificate

#print axioms
  YMGap.Continuum.BF4PhysicalBoundaryCutoffTwoSectorRawKernelCertificate.cutoffTwoSectorComputedRawKernel_eqv_raw
'''
    return data_source, row_sources, root_source


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--coupling", default="1/2")
    parser.add_argument("--jobs", type=int, default=15)
    parser.add_argument(
        "--output-dir", type=Path,
        default=Path("lean/YMGap/Continuum"),
    )
    arguments = parser.parse_args()
    data_source, row_sources, root_source = render_bundle(
        coupling=Fraction(arguments.coupling), jobs=arguments.jobs
    )
    output_dir = arguments.output_dir
    rows_dir = output_dir / "BF4PhysicalBoundaryCutoffTwoSectorRawKernelRows"
    rows_dir.mkdir(parents=True, exist_ok=True)

    def write_if_changed(path: Path, source: str) -> None:
        if path.exists() and path.read_text() == source:
            return
        path.write_text(source)

    data_path = output_dir / "BF4PhysicalBoundaryCutoffTwoSectorRawKernelData.lean"
    root_path = output_dir / "BF4PhysicalBoundaryCutoffTwoSectorRawKernelCertificate.lean"
    write_if_changed(data_path, data_source)
    for row, source in enumerate(row_sources):
        write_if_changed(rows_dir / f"Row{row:02d}.lean", source)
    write_if_changed(root_path, root_source)
    total_bytes = len(data_source) + len(root_source) + sum(map(len, row_sources))
    print(
        f"wrote {data_path}, {len(row_sources)} row shards, and {root_path} "
        f"({total_bytes} bytes)"
    )


if __name__ == "__main__":
    main()
