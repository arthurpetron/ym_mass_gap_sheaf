#!/usr/bin/env python3
"""Emit an apply_patch payload for the BF4 translation-step universe.

The generated code list is diagnostic input only.  Lean reconstructs each
proof-carrying step, kernel-checks every coordinate identity, and separately
checks that every geometric ledger step has a listed code.
"""

from __future__ import annotations

import importlib.util
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DIAGNOSTIC = ROOT / "scripts" / "diagnose_bf4_surface_word_semantics.py"
MODULE = "BF4ExactCutoffOneSurfaceForestGaugeStepCoordinateCheck"
LEAN_DIR = ROOT / "lean" / "YMGap" / "Continuum"
CHUNK_SIZE = 16


def load_geometry():
    spec = importlib.util.spec_from_file_location("bf4_word_geometry", DIAGNOSTIC)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def distinct_step_codes() -> list[int]:
    geometry = load_geometry()
    active_order = [
        0, 20, 12, 1, 21, 7, 2, 22,
        4, 3, 13, 8, 14, 5, 9, 6,
        23, 15, 24, 10, 16, 11, 25, 17,
        26, 18, 27, 19, 28, 29, 30, 31,
    ]
    block = {edge: index for index, edge in enumerate(active_order)}
    steps: set[tuple[int, int, int, int]] = set()
    for mask in geometry.masks():
        paths = geometry.root_paths(mask)
        for chord in geometry.chords(mask):
            tail, head = geometry.ENDPOINTS[chord]
            selected = block[chord]
            for edge, reverse in reversed(paths[tail]):
                steps.add((selected, block[edge], 0, 0 if reverse else 1))
            for edge, reverse in reversed(paths[head]):
                steps.add((selected, block[edge], 1, 1 if reverse else 0))
    return sorted(
        selected + 32 * (multiplier + 32 * (side + 2 * orientation))
        for selected, multiplier, side, orientation in steps
    )


def render_nat_list(values: list[int]) -> str:
    if not values:
        return "[]"
    rows = [values[index:index + 12] for index in range(0, len(values), 12)]
    return "[" + ",\n    ".join(", ".join(map(str, row)) for row in rows) + "]"


def base_file(chunks: list[list[int]]) -> str:
    chunk_defs = "\n\n".join(
        f"def surfaceForestGaugeStepUniverseCodes{index:02d} : List Nat :=\n"
        f"  {render_nat_list(chunk)}"
        for index, chunk in enumerate(chunks)
    )
    joined = " ++\n    ".join(
        f"surfaceForestGaugeStepUniverseCodes{index:02d}"
        for index in range(len(chunks))
    )
    return f'''/-
# Deduplicated finite translation-step universe for the BF4 surface bridge

The 128 geometric ledgers contain 7,551 elementary shears but only 513
distinct `(selected, multiplier, side, orientation)` shapes.  The literal
code table below is generated by `computations/generate_bf4_step_universe.py`.
It is not trusted: Lean decodes the table, checks every coordinate identity,
and separately checks coverage of the actual proof-carrying ledgers.

No `Classical.*`, `native_decide`, `sorry`, custom axiom, choice, or
noncomputable declaration is used.
-/

import YMGap.Continuum.BF4ExactCutoffOneSurfaceForestGaugeWordCarrierSemantics

namespace YMGap.Continuum.{MODULE}

set_option maxRecDepth 200000
set_option maxHeartbeats 120000000

open YMGap.Continuum.BF4CutoffOneBinarySurfaceCertificate
open YMGap.Continuum.BF4ExactCutoffOneSurfaceForestGaugeTranslation
open YMGap.Continuum.BF4ExactCutoffOneSurfaceForestGaugeWordCarrierSemantics
open YMGap.Continuum.SU2QuaternionSelectedHaarTranslationChain

def selectedTranslationSideCode : SelectedTranslationSide → Nat
  | .left => 0
  | .right => 1

def selectedMultiplierOrientationCode : SelectedMultiplierOrientation → Nat
  | .direct => 0
  | .inverse => 1

def rawSelectedTranslationStepCode
    (step : RawSelectedTranslationStep) : Nat :=
  step.selected + 32 * (step.multiplier + 32 *
    (selectedTranslationSideCode step.side +
      2 * selectedMultiplierOrientationCode step.multiplierOrientation))

def selectedTranslationStepCode
    (step : SelectedTranslationStep 31) : Nat :=
  step.selected + 32 * (step.multiplier + 32 *
    (selectedTranslationSideCode step.side +
      2 * selectedMultiplierOrientationCode step.multiplierOrientation))

def decodeRawSelectedTranslationStep
    (code : Nat) : RawSelectedTranslationStep where
  selected := code % 32
  multiplier := (code / 32) % 32
  side := if (code / 1024) % 2 = 0 then .left else .right
  multiplierOrientation :=
    if (code / 2048) % 2 = 0 then .direct else .inverse

def decodedSelectedTranslationStepCoordinateCheck (code : Nat) : Bool :=
  if hvalid : rawSelectedTranslationStepValid 31
      (decodeRawSelectedTranslationStep code) = true then
    let step := (decodeRawSelectedTranslationStep code).certify hvalid
    selectedTranslationStepCoordinateCheck (by decide : 0 < 31)
      step step.selected
  else false

{chunk_defs}

def surfaceForestGaugeStepUniverseCodes : List Nat :=
  {joined}

def surfaceForestGaugeStepUniverseCoordinateCheck : Bool :=
  surfaceForestGaugeStepUniverseCodes.all
    decodedSelectedTranslationStepCoordinateCheck

def binarySurfaceForestGaugeStepUniverseCoverageCheck : Bool :=
  binarySurfaceMasks.attach.all fun maskEntry =>
    (surfaceForestGaugeTranslationSteps maskEntry.1 maskEntry.2).all fun step =>
      decide (selectedTranslationStepCode step ∈
        surfaceForestGaugeStepUniverseCodes)

theorem surfaceForestGaugeStepUniverseCodes_length :
    surfaceForestGaugeStepUniverseCodes.length = 513 := by
  decide

end YMGap.Continuum.{MODULE}
'''


def slice_file(index: int) -> str:
    return f'''import YMGap.Continuum.{MODULE}

namespace YMGap.Continuum.{MODULE}

set_option maxRecDepth 200000
set_option maxHeartbeats 120000000

theorem surfaceForestGaugeStepUniverseCodes{index:02d}_coordinateCheck_true :
    surfaceForestGaugeStepUniverseCodes{index:02d}.all
      decodedSelectedTranslationStepCoordinateCheck = true := by
  decide

end YMGap.Continuum.{MODULE}

#print axioms YMGap.Continuum.{MODULE}.surfaceForestGaugeStepUniverseCodes{index:02d}_coordinateCheck_true
'''


def emit_patch() -> str:
    codes = distinct_step_codes()
    assert len(codes) == 513
    chunks = [codes[index:index + CHUNK_SIZE]
              for index in range(0, len(codes), CHUNK_SIZE)]
    lines = ["*** Begin Patch"]
    base = LEAN_DIR / f"{MODULE}.lean"
    lines.append(f"*** Delete File: {base}")
    lines.append(f"*** Add File: {base}")
    lines.extend("+" + line for line in base_file(chunks).splitlines())
    for index in range(len(chunks)):
        path = LEAN_DIR / f"{MODULE}{index:02d}.lean"
        if path.exists():
            lines.append(f"*** Delete File: {path}")
        lines.append(f"*** Add File: {path}")
        lines.extend("+" + line for line in slice_file(index).splitlines())
    lines.append("*** End Patch")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    print(emit_patch(), end="")
