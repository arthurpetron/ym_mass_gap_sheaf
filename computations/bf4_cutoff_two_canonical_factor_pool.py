def _write_if_changed(path: Path, source: str) -> None:
    if path.exists() and path.read_text() == source:
        return
    path.write_text(source)


def main() -> None:
    bundle = build_pool()
    _write_if_changed(
        LEAN / "BF4PhysicalBoundaryCutoffTwoCanonicalFactorPool.lean",
        render_data(bundle),
    )
    _write_if_changed(
        LEAN / "BF4PhysicalBoundaryCutoffTwoCanonicalCommonTransport.lean",
        render_common_transport(),
    )
    source_dir = LEAN / "BF4PhysicalBoundaryCutoffTwoCanonicalSourceTransports"
    source_dir.mkdir(parents=True, exist_ok=True)
    for index in range(65):
        _write_if_changed(
            source_dir / f"State{index:02d}.lean",
            render_source_transport(index),
        )
    print("generated 81 canonical factors, one common transport, and 65 source transports")


if __name__ == "__main__":
    main()
