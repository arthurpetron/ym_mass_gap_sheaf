#!/usr/bin/env python3
"""Emit the exact Lean data for the lower-six next-slope floor charts.

The mathematical derivation lives in
``lower_six_tail_second_flux_certificate.py``.  This emitter only serializes
the already-derived exact integer tables and sparse cleared polynomial.  No
floating-point value is used.
"""

from __future__ import annotations

import importlib.util
import math
from pathlib import Path

import sympy as sp


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "computations/lower_six_tail_second_flux_certificate.py"
OUTPUT = (
    ROOT
    / "lean/YMGap/Continuum/HarmonicLowerSixTailSlopeFloorCertificateData.lean"
)
LEAN_DIR = ROOT / "lean/YMGap/Continuum"


def load_source():
    spec = importlib.util.spec_from_file_location("lower_six_certificate", SOURCE)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot load {SOURCE}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def lcm_denominators(values) -> int:
    answer = 1
    for value in values:
        answer = math.lcm(answer, value.denominator)
    return answer


def scaled_rows(bernstein, degree_x: int, degree_y: int):
    scale = lcm_denominators(bernstein.values())
    rows = []
    for i in range(degree_x + 1):
        row = []
        for j in range(degree_y + 1):
            value = bernstein[i, j]
            row.append(value.numerator * (scale // value.denominator))
        rows.append(row)
    return scale, rows


def lean_rows(rows) -> str:
    rendered = []
    for row in rows:
        rendered.append("  [" + ", ".join(str(value) for value in row) + "]")
    return "[\n" + ",\n".join(rendered) + "\n]"


def lean_terms(terms) -> str:
    rendered = [
        f"  ({i}, {j}, {coefficient})" for (i, j), coefficient in terms
    ]
    return "[\n" + ",\n".join(rendered) + "\n]"


def block_physical_terms(source, rows, chart: str, start: int, stop: int):
    """Expand one small consecutive Bernstein-row block after substitution.

    This expansion is serialized only as a proposed sparse identity.  Lean's
    proved eager normalizer checks the block identity in the kernel.
    """
    degree_x, degree_y = 15, 8
    D, n = source.D, source.n
    if chart == "A":
        x0 = sp.Integer(source.MODE_CHART_BASE)
        x1 = n - source.MODE_CHART_BASE
        y0, y1 = D - n**2, 2 * n**2 - D
    elif chart == "B":
        x0 = sp.Integer(source.MODE_CHART_BASE)
        x1 = n - source.MODE_CHART_BASE
        y0, y1 = n * (2 * D - n), 2 * n * (n**2 - D)
    else:
        raise ValueError(chart)

    expression = 0
    for i in range(start, stop):
        for j in range(degree_y + 1):
            expression += (
                rows[i][j]
                * math.comb(degree_x, i)
                * math.comb(degree_y, j)
                * x0**i
                * x1 ** (degree_x - i)
                * y0**j
                * y1 ** (degree_y - j)
            )
    polynomial = sp.Poly(sp.expand(expression), D, n)
    answer = []
    for (degree_d, degree_n), coefficient in polynomial.terms():
        assert coefficient.q == 1
        answer.append(((degree_d, degree_n), int(coefficient)))
    return answer


def lean_block_data(source, rows, chart: str, block_size: int = 2) -> str:
    pieces = []
    block_names = []
    for block, start in enumerate(range(0, len(rows), block_size)):
        stop = min(start + block_size, len(rows))
        prefix = f"lowerSixTailSlopeFloorChart{chart}Block{block}"
        block_names.append(prefix + "PhysicalExpr")
        pieces.append(
            f"def {prefix}Rows : List (List Int) :=\n"
            f"  (lowerSixTailSlopeFloorChart{chart}Rows.drop {start}).take "
            f"{stop - start}\n\n"
            f"def {prefix}Terms : List (Nat × Nat × Int) :=\n"
            f"{lean_terms(block_physical_terms(source, rows, chart, start, stop))}\n\n"
            f"def {prefix}PhysicalExpr : PE :=\n"
            f"  bivariatePowerExpr {prefix}Terms\n"
        )
    sum_expr = ".const 0"
    for name in reversed(block_names):
        sum_expr = f".add {name} ({sum_expr})"
    pieces.append(
        f"def lowerSixTailSlopeFloorChart{chart}BlockPhysicalSumExpr : PE :=\n"
        f"  {sum_expr}\n"
    )
    return "\n".join(pieces)


def write_block_proof(chart: str, block: int, start: int) -> Path:
    prefix = f"lowerSixTailSlopeFloorChart{chart}Block{block}"
    path = LEAN_DIR / (
        f"HarmonicLowerSixTailSlopeFloorCertificateBlock{chart}{block}.lean"
    )
    path.write_text(f'''/-
# Kernel check for slope-floor chart {chart}, Bernstein rows {start}-{start + 1}

Generated by `computations/generate_lower_six_tail_slope_floor_lean.py`.
The sparse identity data are untrusted input until the eager normalizer closes
`chart{chart}Block{block}_physical_identity` below.
-/

import YMGap.Continuum.HarmonicLowerSixTailSlopeFloorCertificateData

namespace YMGap.Continuum.HarmonicLowerSixTailSlopeFloorCertificateBlocks

set_option maxHeartbeats 8000000
set_option maxRecDepth 100000

open YMGap.Continuum.CoreBResidualSimplex
open YMGap.Continuum.HarmonicLowerSixTailSlopeFloorCertificateData
open YMGap.Continuum.TensorBernsteinHomogeneousCertificate

theorem chart{chart}Block{block}_coefficients_nonnegative :
    IntegerRowsNonnegative {prefix}Rows = true := by
  rfl

theorem chart{chart}Block{block}_physical_identity :
    fastNormalize
        (substitute lowerSixTailSlopeFloorChart{chart}Substitution
          (homogeneousTensorBlockExpr 15 8 {start} {prefix}Rows)) =
      fastNormalize {prefix}PhysicalExpr := by
  rfl

#print axioms chart{chart}Block{block}_coefficients_nonnegative
#print axioms chart{chart}Block{block}_physical_identity

end YMGap.Continuum.HarmonicLowerSixTailSlopeFloorCertificateBlocks
''')
    return path


def write_block_umbrella() -> Path:
    path = LEAN_DIR / "HarmonicLowerSixTailSlopeFloorCertificateBlocks.lean"
    imports = []
    for chart in ("A", "B"):
        for block in range(8):
            imports.append(
                "import YMGap.Continuum."
                f"HarmonicLowerSixTailSlopeFloorCertificateBlock{chart}{block}"
            )
    path.write_text("\n".join(imports) + "\n")
    return path


def main() -> None:
    source = load_source()
    poly = source.sp.Poly(source.L1NUM, source.D, source.n)

    polynomial_scale = 1
    for _, coefficient in poly.terms():
        polynomial_scale = math.lcm(polynomial_scale, int(coefficient.q))
    cleared_terms = []
    for degree, coefficient in poly.terms():
        scaled = source.exact_fraction(coefficient) * polynomial_scale
        assert scaled.denominator == 1
        cleared_terms.append((degree, scaled.numerator))

    tables = {}
    for chart, transform in (
        ("A", source.chart_a_power_coefficients),
        ("B", source.chart_b_power_coefficients),
    ):
        power, exponent = transform(poly)
        assert exponent == 16
        degree_x = max(i for i, _ in power)
        degree_y = max(j for _, j in power)
        assert (degree_x, degree_y) == (15, 8)
        bernstein = source.bernstein_coefficients(power, degree_x, degree_y)
        assert all(value >= 0 for value in bernstein.values())
        table_scale, rows = scaled_rows(bernstein, degree_x, degree_y)
        assert table_scale % polynomial_scale == 0
        tables[chart] = (table_scale, rows)

    scale_a, rows_a = tables["A"]
    scale_b, rows_b = tables["B"]
    quotient_a = scale_a // polynomial_scale
    quotient_b = scale_b // polynomial_scale
    blocks_a = lean_block_data(source, rows_a, "A")
    blocks_b = lean_block_data(source, rows_b, "B")

    text = f'''/-
# Generated exact lower-six slope-floor Bernstein data

Generated by `computations/generate_lower_six_tail_slope_floor_lean.py` from
exact `Fraction` arithmetic.  The raw polynomial is `2520 * L1NUM`; the two
tables are the native degree `(15,8)` tensor Bernstein certificates on charts
A and B.  Regenerate instead of hand-editing the integer data.
-/

import YMGap.Continuum.TensorBernsteinHomogeneousCertificate

namespace YMGap.Continuum.HarmonicLowerSixTailSlopeFloorCertificateData

open YMGap.Continuum.TensorBernsteinHomogeneousCertificate

private abbrev PE := RingNormaliser.PolyExpr

def lowerSixTailNextSlopeFloorPolynomialScale : Nat := {polynomial_scale}

def lowerSixTailNextSlopeFloorClearedTerms : List (Nat × Nat × Int) :=
{lean_terms(cleared_terms)}

def lowerSixTailNextSlopeFloorClearedExpr : PE :=
  bivariatePowerExpr lowerSixTailNextSlopeFloorClearedTerms

def lowerSixTailSlopeFloorChartARows : List (List Int) :=
{lean_rows(rows_a)}

def lowerSixTailSlopeFloorChartAExpr : PE :=
  homogeneousTensorExpr 15 8 lowerSixTailSlopeFloorChartARows

def lowerSixTailSlopeFloorChartAScale : Int := {scale_a}
def lowerSixTailSlopeFloorChartAQuotient : Int := {quotient_a}

/-- Chart A homogeneous coordinates: `{source.MODE_CHART_BASE}`, `N-{source.MODE_CHART_BASE}`, `D-N^2`,
`2*N^2-D`. -/
def lowerSixTailSlopeFloorChartASubstitution : Nat → PE
  | 0 => .const {source.MODE_CHART_BASE}
  | 1 => .add (.var 1) (.neg (.const {source.MODE_CHART_BASE}))
  | 2 => .add (.var 0) (.neg (.mul (.var 1) (.var 1)))
  | 3 => .add
      (.mul (.const 2) (.mul (.var 1) (.var 1)))
      (.neg (.var 0))
  | _ => .const 0

def lowerSixTailSlopeFloorChartAPhysicalExpr : PE :=
  .mul (.const lowerSixTailSlopeFloorChartAQuotient)
    (.mul (.pow (.var 1) 15) lowerSixTailNextSlopeFloorClearedExpr)

{blocks_a}

def lowerSixTailSlopeFloorChartBRows : List (List Int) :=
{lean_rows(rows_b)}

def lowerSixTailSlopeFloorChartBExpr : PE :=
  homogeneousTensorExpr 15 8 lowerSixTailSlopeFloorChartBRows

def lowerSixTailSlopeFloorChartBScale : Int := {scale_b}
def lowerSixTailSlopeFloorChartBQuotient : Int := {quotient_b}

/-- Chart B homogeneous coordinates: `{source.MODE_CHART_BASE}`, `N-{source.MODE_CHART_BASE}`,
`N*(2D-N)`, `2N*(N^2-D)`. -/
def lowerSixTailSlopeFloorChartBSubstitution : Nat → PE
  | 0 => .const {source.MODE_CHART_BASE}
  | 1 => .add (.var 1) (.neg (.const {source.MODE_CHART_BASE}))
  | 2 => .mul (.var 1)
      (.add (.mul (.const 2) (.var 0)) (.neg (.var 1)))
  | 3 => .mul (.mul (.const 2) (.var 1))
      (.add (.mul (.var 1) (.var 1)) (.neg (.var 0)))
  | _ => .const 0

def lowerSixTailSlopeFloorChartBPhysicalExpr : PE :=
  .mul (.const lowerSixTailSlopeFloorChartBQuotient)
    (.mul (.pow (.var 1) 15)
      (.mul
        (.pow
          (.add (.mul (.const 2) (.var 1)) (.neg (.const 1))) 8)
        lowerSixTailNextSlopeFloorClearedExpr))

{blocks_b}

#print axioms lowerSixTailNextSlopeFloorClearedExpr
#print axioms lowerSixTailSlopeFloorChartAExpr
#print axioms lowerSixTailSlopeFloorChartBExpr

end YMGap.Continuum.HarmonicLowerSixTailSlopeFloorCertificateData
'''
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    for chart in ("A", "B"):
        for block, start in enumerate(range(0, 16, 2)):
            path = write_block_proof(chart, block, start)
            print(f"wrote {path.relative_to(ROOT)}")
    umbrella = write_block_umbrella()
    print(f"wrote {umbrella.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
