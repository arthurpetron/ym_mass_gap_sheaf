#!/usr/bin/env python3
"""Emit cheap local-to-aggregate row identities for the E8/E9 tables.

The expensive transform relations live in the generated slice modules from
``generate_lower_six_tail_envelope_lean.py``.  These companion modules only
identify each seven-row shard with the corresponding rows of the balanced
aggregate list, allowing semantic consumers to use one global coefficient
function without re-running a large transform.
"""

from __future__ import annotations

from pathlib import Path


ROW_SHARD_SIZE = 7
CASES = [
    ("E8", "A", 83, 44),
    ("E9", "A", 87, 44),
    ("E8", "B", 85, 44),
    ("E9", "B", 87, 44),
]


def render(label: str, chart: str, degree_x: int, degree_y: int,
           shard: int) -> str:
    stem = f"tailEnvelope{label}Chart{chart}"
    module = f"HarmonicLowerSixTailEnvelopeCertificate{label}Chart{chart}Rows"
    namespace = (
        "YMGap.Continuum."
        f"HarmonicLowerSixTailEnvelopeCertificate{label}Chart{chart}"
    )
    start = shard * ROW_SHARD_SIZE
    height = min(ROW_SHARD_SIZE, degree_x + 1 - start)
    assert height > 0
    lines = [
        "/-",
        f"# Local-to-aggregate {label} chart-{chart} row identities {shard}",
        "",
        "Generated by",
        "`computations/generate_lower_six_tail_envelope_aggregate_slices.py`.",
        "-/",
        "",
        f"import YMGap.Continuum.{module}",
        "import YMGap.Continuum.HarmonicLowerSixTailEnvelopeCoefficientKernel",
        "",
        f"namespace {namespace}",
        "",
        "set_option maxHeartbeats 10000000",
        "",
        "open YMGap.Continuum.TensorBernsteinSeparableReconstruction",
        "open YMGap.Continuum.HarmonicLowerSixTailEnvelopeCoefficientKernel",
        "open YMGap.Continuum.HarmonicLowerSixTailEnvelopeCertificateRows",
        "",
    ]
    for suffix, gate in [
        ("ScaledPower", "power"),
        ("XPascal", "xPascal"),
        ("Bernstein", "bernstein"),
        ("PreChart", "preChart"),
    ]:
        theorem = f"{stem}_{gate}_aggregate_slice{shard}"
        lines.extend([
            f"theorem {theorem} :",
            f"    GridRelationSlice {start} {height} {degree_y + 1}",
            f"      (gridCoeff {stem}{suffix}Rows{shard})",
            f"      (gridCoeff {stem}{suffix}Rows) = true := by",
            "  rfl",
            "",
        ])
    for gate in ["power", "xPascal", "bernstein", "preChart"]:
        lines.append(f"#print axioms {stem}_{gate}_aggregate_slice{shard}")
    lines.extend(["", f"end {namespace}", ""])
    return "\n".join(lines)


def main() -> None:
    repo = Path(__file__).resolve().parents[1]
    continuum = repo / "lean" / "YMGap" / "Continuum"
    count = 0
    for label, chart, degree_x, degree_y in CASES:
        shard_count = (degree_x + ROW_SHARD_SIZE) // ROW_SHARD_SIZE
        for shard in range(shard_count):
            path = continuum / (
                f"HarmonicLowerSixTailEnvelopeCertificate{label}Chart{chart}"
                f"AggregateSlice{shard}.lean"
            )
            path.write_text(render(label, chart, degree_x, degree_y, shard))
            count += 1
    print(f"wrote {count} aggregate-slice modules")


if __name__ == "__main__":
    main()
